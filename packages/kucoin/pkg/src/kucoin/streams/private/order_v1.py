"""`/spotMarket/tradeOrders` — Legacy order-lifecycle channel, superseded in most integrations by V2 (`/spotMarket/tradeOrdersV2`) but still documented and live -- pushes every lifecycle event of the authenticated account's Spot/Margin orders except the `received`/`new` stage V2 added."""

from typing_extensions import Any, Literal, NotRequired
from typed_core.util import StreamManager
from typed_core.validation import TypedDict, validator
from kucoin.types import WsSubscriptionAck
from kucoin.core import StreamEndpoint


class OrderChangeEventV1(TypedDict):
  """One order lifecycle push -- the unwrapped `data` field of the raw WebSocket frame (`SocketStreamClient.authed_subscribe` extracts `data` before handing the stream to the caller; see `spec/core.md`'s WebSocket section). Same shape as `OrderChangeEvent` (Order V2) except this channel has no `received` event and never carries a `new` status transition -- V2's own addition over this legacy channel."""

  clientOid: str
  """Client-assigned order id, echoed back from the placement request."""
  orderId: str
  """Order id assigned by the matching system."""
  orderTime: int
  """Unix milliseconds when the gateway received the order."""
  orderType: Literal['limit', 'market']
  """User-specified order type."""
  originSize: str
  """User-specified order size at placement."""
  side: Literal['buy', 'sell']
  """Order side."""
  status: Literal['new', 'open', 'match', 'done']
  """Order status: `new` (entered the matching system), `open` (resting in the order book as a maker order), `match` (a taker order currently executing), `done` (fully executed, filled or canceled)."""
  symbol: str
  """Trading pair symbol, for example `BTC-USDT`."""
  ts: int
  """Unix nanoseconds when the matching engine received/generated this event."""
  type: Literal['open', 'match', 'update', 'filled', 'canceled']
  """Event driving this push: `open` (resting in the order book), `match` (matched against a counterparty), `update` (modified -- partial cancel or self-trade-prevention trigger), `filled` (fully executed), `canceled` (fully canceled). Unlike Order V2, there is no `received` value on this legacy channel."""
  price: NotRequired[str]
  """Order price. Present on limit-order pushes."""
  size: NotRequired[str]
  """User-specified order size, echoed on most event types."""
  canceledSize: NotRequired[str]
  """Cumulative amount canceled. Present on `canceled`."""
  filledSize: NotRequired[str]
  """Cumulative amount filled. Present on `open`, `match`, `filled`, `canceled`."""
  remainSize: NotRequired[str]
  """Remaining unfilled size. Present on `open`, `match`, `update`, `filled`, `canceled`."""
  remainFunds: NotRequired[str]
  """Remaining unfilled funds. Present on `update`, `filled`, `canceled`."""
  oldSize: NotRequired[str]
  """Order size before this update. Present only on `update`."""
  matchPrice: NotRequired[str]
  """Execution price of this fill. Present only on `match`."""
  matchSize: NotRequired[str]
  """Amount matched in this fill. Present only on `match`."""
  tradeId: NotRequired[str]
  """Trade id generated by the matching engine for this fill. Present only on `match`."""
  liquidity: NotRequired[Literal['taker', 'maker']]
  """Liquidity role of this fill. Present only on `match`. Reads `taker` even for a maker order matched against a hidden/iceberg counterparty -- see `feeType` for the actual fee charged."""
  feeType: NotRequired[Literal['takerFee', 'makerFee']]
  """Actual fee type charged for this fill. Present only on `match`."""


_Type = OrderChangeEventV1
validate_update = validator[_Type](_Type)  # type: ignore


class OrderV1(StreamEndpoint):
  """Subscribe to `/spotMarket/tradeOrders` — mixed into `Private`, the product exposing `streams.spot_margin.order_v1`."""

  def order_v1(
    self,
    *,
    validate: bool | None = None,
  ) -> StreamManager[OrderChangeEventV1, Any, Any]:
    """Legacy order-lifecycle channel, superseded in most integrations by V2 (`/spotMarket/tradeOrdersV2`) but still documented and live -- pushes every lifecycle event of the authenticated account's Spot/Margin orders except the `received`/`new` stage V2 added.

    Args:
      validate: Whether to validate pushed payloads against the expected schema.

    Returns:
      A manager for the subscription stream.

    Raises:
      AuthError: This connection has no credentials — this is a private channel, unreachable from a `public=True` client.

    References:
      - [KuCoin API docs](https://www.kucoin.com/docs-new)
    """
    return self.authed_subscribe(
      '/spotMarket/tradeOrders',
      validator=validate_update,
      validate=validate,
    )
