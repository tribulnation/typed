"""The Binance client root.

Product-grouped composition (`spec/status.md`'s 2026-08-20 entry): `Binance` composes five
top-level products (`spot`, `usdm_futures`, `coinm_futures`, `options`, `portfolio_margin`),
each itself a plain `@dataclass(kw_only=True)` composing that product's own transports --
`http`, `streams`/`public_streams`/`private_streams`, `ws` -- as sibling fields (S11/S23).
Every generated endpoint class is generated by `codegen/python.py` from its own nested
`spec/endpoints/<product>/<transport>` tree, into the matching nested package
(`typed_binance.coinm_futures.streams.Streams`, `typed_binance.usdm_futures.ws.Ws`, ...) --
each generated root class is named after its transport alone (`Http`/`Streams`/
`PublicStreams`/`PrivateStreams`/`Ws`), so this module imports every one of them aliased to
a product-qualified name before wiring it into the right transport slot.

Account/order push events over the Spot WS API connection are `spot.ws.subscribe_user_data()`,
inherited unchanged from `WsRpcEndpoint` (via Binance's `userDataStream.subscribe.signature`
-- confirmed working with HMAC credentials live, unlike `session.logon` which Binance
restricts to Ed25519) -- not renamed or wrapped here, since the generated `user_data`
attribute already names the spec'd sub-router.
"""

