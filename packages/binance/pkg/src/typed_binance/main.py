@dataclass(kw_only=True)
class Spot:
  """Binance Spot: REST (`http`), market-data streams (`streams`), and the request/reply
  WS API (`ws`) -- account/order push events over that same WS API connection are
  `ws.subscribe_user_data()` (see this module's own docstring).
  """

  http: SpotHttp
  streams: Streams
  ws: WsApi

  async def __aenter__(self):
    await asyncio.gather(
      self.http.__aenter__(), self.streams.__aenter__(), self.ws.__aenter__()
    )
    return self

  async def __aexit__(self, exc_type, exc_value, traceback):
    await asyncio.gather(
      self.http.__aexit__(exc_type, exc_value, traceback),
      self.streams.__aexit__(exc_type, exc_value, traceback),
      self.ws.__aexit__(exc_type, exc_value, traceback),
    )


@dataclass(kw_only=True)
class UsdMFutures:
  """Binance USD-M Futures: REST (`http`), two market-data streams connections
  (`streams` for the general channel set, `public_streams` specifically for order-book
  channels, which Binance serves on a separate connection), the private user-data stream
  (`private_streams`), and a WS API (`ws`).
  """

  http: UsdMFuturesHttp
  streams: UsdMFuturesStreams
  public_streams: UsdMFuturesPublicStreams
  private_streams: UsdMFuturesPrivateStreams
  ws: UsdMFuturesWsApi

  async def __aenter__(self):
    await asyncio.gather(
      self.http.__aenter__(),
      self.streams.__aenter__(),
      self.public_streams.__aenter__(),
      self.private_streams.__aenter__(),
      self.ws.__aenter__(),
    )
    return self

  async def __aexit__(self, exc_type, exc_value, traceback):
    await asyncio.gather(
      self.http.__aexit__(exc_type, exc_value, traceback),
      self.streams.__aexit__(exc_type, exc_value, traceback),
      self.public_streams.__aexit__(exc_type, exc_value, traceback),
      self.private_streams.__aexit__(exc_type, exc_value, traceback),
      self.ws.__aexit__(exc_type, exc_value, traceback),
    )


