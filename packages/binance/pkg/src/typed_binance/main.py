"""The Binance client root.

Product-grouped composition (`spec/status.md`'s 2026-08-20 entry): `Binance` composes five
top-level products (`spot`, `usdm_futures`, `coinm_futures`, `options`, `portfolio_margin`),
each itself a plain `@dataclass(kw_only=True)` composing that product's own transports --
`http`, `streams`/`public_streams`/`private_streams`, `ws` -- as sibling fields (S11/S23).
Every generated endpoint class is still generated by `codegen/python.py` from its own
`spec/endpoints/<surface>` tree exactly as before (`binance.spot.Spot`,
`binance.usdm_futures.UsdMFutures`, ...); this module just imports each one under an
aliased name where it collides with a product's own composite class name, and wires it into
the right transport slot.

The three WS API surfaces (`WsApi`, `UsdMFuturesWsApi`, `CoinMFuturesWsApi`) are the one
exception: each subclasses its generated counterpart to add `ping()`, hand-written because
no `ping` endpoint exists anywhere in the spec -- see the method's own docstring. Once a spec
exists for it, generation supersedes this. Account/order push events over the Spot WS API
connection are `spot.ws.subscribe_user_data()`, inherited unchanged from `WsRpcEndpoint` (see
`WsApi`'s own docstring for why it isn't wrapped or renamed here).
"""

