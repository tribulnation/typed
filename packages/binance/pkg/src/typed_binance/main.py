"""The Binance client root.

One field per surface (see `spec/core.md`), composed as peers. Every surface's endpoint
class is generated by `codegen/python.py` from its own `spec/endpoints/<surface>` tree
(`binance.spot.Spot`, `binance.usdm_futures.UsdMFutures`, ...) — this module just wires
each one to the transport its surface needs.

The three WS API surfaces (`WsApi`, `UsdMFuturesWsApi`, `CoinMFuturesWsApi`) are the one
exception: each subclasses its generated counterpart to add `ping()`, hand-written because
no `ping` endpoint exists anywhere in the spec — see the method's own docstring. Once a spec
exists for it, generation supersedes this. Account/order push events over the Spot WS API
connection are `WsApi.subscribe_user_data()`, inherited unchanged from `WsRpcEndpoint` (see
`WsApi`'s own docstring for why it isn't wrapped or renamed here).
"""

from dataclasses import dataclass
import asyncio

from typed_binance.coinm_futures import CoinMFutures
from typed_binance.coinm_futures_streams import CoinMFuturesStreams
from typed_binance.coinm_futures_ws_api import CoinMFuturesWsApi as _CoinMFuturesWsApi
from typed_binance.options import Options
from typed_binance.options_streams import OptionsStreams
from typed_binance.portfolio_margin import PortfolioMargin
from typed_binance.spot import Spot
from typed_binance.streams import Streams
from typed_binance.usdm_futures import UsdMFutures
from typed_binance.usdm_futures_public_streams import UsdMFuturesPublicStreams
from typed_binance.usdm_futures_streams import UsdMFuturesStreams
from typed_binance.usdm_futures_ws_api import UsdMFuturesWsApi as _UsdMFuturesWsApi
from typed_binance.ws_api import WsApi as _WsApi

from .core.auth import resolve_credentials
from .core.transport.http import HttpRpcClient
from .core.transport.ws.api import SocketRpcClient
from .core.transport.ws.streams import SocketStreamClient


class WsApi(_WsApi):
  """Spot WS API (`wss://ws-api.binance.com/ws-api/v3`) — the generated request/response
  surface (including the generated `user_data` sub-router, `session_subscriptions`/
  `subscribe_listen_token`), plus `ping`. Account/order push events over this same
  connection are `WsRpcEndpoint.subscribe_user_data()` (inherited, via Binance's
  `userDataStream.subscribe.signature` — confirmed working with HMAC credentials live,
  unlike `session.logon` which Binance restricts to Ed25519) — not renamed or wrapped
  here, since the generated `user_data` attribute already names the spec'd sub-router.
  """

  async def ping(self) -> None:
    """Test WS API connectivity. Hand-written: no `ping` endpoint exists in the spec."""
    await self.request('ping')


class UsdMFuturesWsApi(_UsdMFuturesWsApi):
  """USD-M Futures WS API (`wss://ws-fapi.binance.com/ws-fapi/v1`) — the generated
  request/response surface, plus `ping`.
  """

  async def ping(self) -> None:
    """Test WS API connectivity. Hand-written: no `ping` endpoint exists in the spec."""
    await self.request('ping')


class CoinMFuturesWsApi(_CoinMFuturesWsApi):
  """COIN-M Futures WS API (`wss://ws-dapi.binance.com/ws-dapi/v1`) — the generated
  request/response surface, plus `ping`.
  """

  async def ping(self) -> None:
    """Test WS API connectivity. Hand-written: no `ping` endpoint exists in the spec."""
    await self.request('ping')


SPOT_URL = 'https://api.binance.com'
USDM_FUTURES_URL = 'https://fapi.binance.com'
COINM_FUTURES_URL = 'https://dapi.binance.com'
OPTIONS_URL = 'https://eapi.binance.com'
PORTFOLIO_MARGIN_URL = 'https://papi.binance.com'
STREAM_URL = 'wss://stream.binance.com:9443/stream'
USDM_FUTURES_STREAM_URL = 'wss://fstream.binance.com/market/stream'
USDM_FUTURES_PUBLIC_STREAM_URL = 'wss://fstream.binance.com/public/stream'
COINM_FUTURES_STREAM_URL = 'wss://dstream.binance.com/stream'
OPTIONS_STREAM_URL = 'wss://nbstream.binance.com/eoptions/stream'
WS_API_URL = 'wss://ws-api.binance.com:443/ws-api/v3'
USDM_FUTURES_WS_API_URL = 'wss://ws-fapi.binance.com/ws-fapi/v1'
COINM_FUTURES_WS_API_URL = 'wss://ws-dapi.binance.com/ws-dapi/v1'


@dataclass(kw_only=True)
class Binance:
  """Binance client.

  Examples:
    ```python
    from typed_binance import Binance

    async with Binance.new(public=True) as client:
      result = await client.spot.market.server_time()
    ```
  """

  spot: Spot
  usdm_futures: UsdMFutures
  coinm_futures: CoinMFutures
  options: Options
  portfolio_margin: PortfolioMargin
  streams: Streams
  usdm_futures_streams: UsdMFuturesStreams
  usdm_futures_public_streams: UsdMFuturesPublicStreams
  coinm_futures_streams: CoinMFuturesStreams
  options_streams: OptionsStreams
  ws_api: WsApi
  usdm_futures_ws_api: UsdMFuturesWsApi
  coinm_futures_ws_api: CoinMFuturesWsApi

  @classmethod
  def new(
    cls,
    *,
    api_key: str | None = None,
    secret: str | None = None,
    public: bool = False,
    recv_window: int | None = None,
    validate: bool = True,
  ):
    """Build a Binance client. Every surface shares one set of credentials — Binance's
    HMAC signing scheme is uniform across REST hosts and, per docs (confirmed live), the
    WS API.

    Args:
      api_key: Binance API key; read from `BINANCE_API_KEY` when omitted.
      secret: HMAC secret; read from `BINANCE_SECRET_KEY` when omitted.
      public: Build a credential-free client — only `NONE`-security endpoints work.
      recv_window: `recvWindow` (ms) sent with every signed request; `None` uses
        Binance's own 5000ms default.
      validate: Validate responses.
    """
    credentials = resolve_credentials(api_key, secret, public=public)
    return cls(
      spot=Spot(
        client=HttpRpcClient(
          base_url=SPOT_URL,
          credentials=credentials,
          recv_window=recv_window,
          validate=validate,
        )
      ),
      usdm_futures=UsdMFutures(
        client=HttpRpcClient(
          base_url=USDM_FUTURES_URL,
          credentials=credentials,
          recv_window=recv_window,
          validate=validate,
        )
      ),
      coinm_futures=CoinMFutures(
        client=HttpRpcClient(
          base_url=COINM_FUTURES_URL,
          credentials=credentials,
          recv_window=recv_window,
          validate=validate,
        )
      ),
      options=Options(
        client=HttpRpcClient(
          base_url=OPTIONS_URL,
          credentials=credentials,
          recv_window=recv_window,
          validate=validate,
        )
      ),
      portfolio_margin=PortfolioMargin(
        client=HttpRpcClient(
          base_url=PORTFOLIO_MARGIN_URL,
          credentials=credentials,
          recv_window=recv_window,
          validate=validate,
        )
      ),
      streams=Streams(client=SocketStreamClient.new(url=STREAM_URL, validate=validate)),
      usdm_futures_streams=UsdMFuturesStreams(
        client=SocketStreamClient.new(url=USDM_FUTURES_STREAM_URL, validate=validate)
      ),
      usdm_futures_public_streams=UsdMFuturesPublicStreams(
        client=SocketStreamClient.new(
          url=USDM_FUTURES_PUBLIC_STREAM_URL, validate=validate
        )
      ),
      coinm_futures_streams=CoinMFuturesStreams(
        client=SocketStreamClient.new(url=COINM_FUTURES_STREAM_URL, validate=validate)
      ),
      options_streams=OptionsStreams(
        client=SocketStreamClient.new(url=OPTIONS_STREAM_URL, validate=validate)
      ),
      ws_api=WsApi(
        client=SocketRpcClient.new(
          url=WS_API_URL,
          credentials=credentials,
          recv_window=recv_window,
          validate=validate,
        )
      ),
      usdm_futures_ws_api=UsdMFuturesWsApi(
        client=SocketRpcClient.new(
          url=USDM_FUTURES_WS_API_URL,
          credentials=credentials,
          recv_window=recv_window,
          validate=validate,
        )
      ),
      coinm_futures_ws_api=CoinMFuturesWsApi(
        client=SocketRpcClient.new(
          url=COINM_FUTURES_WS_API_URL,
          credentials=credentials,
          recv_window=recv_window,
          validate=validate,
        )
      ),
    )

  async def __aenter__(self):
    await asyncio.gather(
      self.spot.__aenter__(),
      self.usdm_futures.__aenter__(),
      self.coinm_futures.__aenter__(),
      self.options.__aenter__(),
      self.portfolio_margin.__aenter__(),
      self.streams.__aenter__(),
      self.usdm_futures_streams.__aenter__(),
      self.usdm_futures_public_streams.__aenter__(),
      self.coinm_futures_streams.__aenter__(),
      self.options_streams.__aenter__(),
      self.ws_api.__aenter__(),
      self.usdm_futures_ws_api.__aenter__(),
      self.coinm_futures_ws_api.__aenter__(),
    )
    return self

  async def __aexit__(self, exc_type, exc_value, traceback):
    await asyncio.gather(
      self.spot.__aexit__(exc_type, exc_value, traceback),
      self.usdm_futures.__aexit__(exc_type, exc_value, traceback),
      self.coinm_futures.__aexit__(exc_type, exc_value, traceback),
      self.options.__aexit__(exc_type, exc_value, traceback),
      self.portfolio_margin.__aexit__(exc_type, exc_value, traceback),
      self.streams.__aexit__(exc_type, exc_value, traceback),
      self.usdm_futures_streams.__aexit__(exc_type, exc_value, traceback),
      self.usdm_futures_public_streams.__aexit__(exc_type, exc_value, traceback),
      self.coinm_futures_streams.__aexit__(exc_type, exc_value, traceback),
      self.options_streams.__aexit__(exc_type, exc_value, traceback),
      self.ws_api.__aexit__(exc_type, exc_value, traceback),
      self.usdm_futures_ws_api.__aexit__(exc_type, exc_value, traceback),
      self.coinm_futures_ws_api.__aexit__(exc_type, exc_value, traceback),
    )
