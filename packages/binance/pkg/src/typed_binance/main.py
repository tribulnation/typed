SPOT_URL = 'https://api.binance.com'
USDM_FUTURES_URL = 'https://fapi.binance.com'
COINM_FUTURES_URL = 'https://dapi.binance.com'
OPTIONS_URL = 'https://eapi.binance.com'
PORTFOLIO_MARGIN_URL = 'https://papi.binance.com'
STREAM_URL = 'wss://stream.binance.com:9443/stream'
USDM_FUTURES_STREAM_URL = 'wss://fstream.binance.com/market/stream'
USDM_FUTURES_PUBLIC_STREAM_URL = 'wss://fstream.binance.com/public/stream'
COINM_FUTURES_STREAM_URL = 'wss://dstream.binance.com/stream'
OPTIONS_STREAM_URL = 'wss://nbstream.binance.com/eoptions/stream'
WS_API_URL = 'wss://ws-api.binance.com:443/ws-api/v3'
USDM_FUTURES_WS_API_URL = 'wss://ws-fapi.binance.com/ws-fapi/v1'
COINM_FUTURES_WS_API_URL = 'wss://ws-dapi.binance.com/ws-dapi/v1'
USDM_FUTURES_PRIVATE_STREAM_URL = 'wss://fstream.binance.com/private/ws'
OPTIONS_PRIVATE_STREAM_URL = 'wss://fstream.binance.com/private/ws'
PORTFOLIO_MARGIN_PRIVATE_STREAM_URL = 'wss://fstream.binance.com/pm/ws'


@dataclass(kw_only=True)
class Binance:
  """Binance client.

  Examples:
    ```python
    from typed_binance import Binance

    async with Binance.new(public=True) as client:
      result = await client.spot.http.market.server_time()
    ```
  """

  spot: Spot
  usdm_futures: UsdMFutures
  coinm_futures: CoinMFutures
  options: Options
  portfolio_margin: PortfolioMargin

  @classmethod
  def new(
    cls,
    *,
    api_key: str | None = None,
    secret_key: str | None = None,
    public: bool = False,
    recv_window: int | None = None,
    validate: bool = True,
  ):
    """Build a Binance client. Every surface shares one set of credentials -- Binance's
    HMAC signing scheme is uniform across REST hosts and, per docs (confirmed live), the
    WS API.

    Args:
      api_key: Binance API key; read from `BINANCE_API_KEY` when omitted.
      secret_key: HMAC secret; read from `BINANCE_SECRET_KEY` when omitted.
      public: Build a credential-free client -- only `NONE`-security endpoints work.
      recv_window: `recvWindow` (ms) sent with every signed request; `None` uses
        Binance's own 5000ms default.
      validate: Validate responses.
    """
    credentials = resolve_credentials(api_key, secret_key, public=public)
    return cls(
      spot=Spot(
        http=SpotHttp(
          client=HttpRpcClient(
            base_url=SPOT_URL,
            credentials=credentials,
            recv_window=recv_window,
            validate=validate,
          )
        ),
        streams=Streams(
          client=SocketStreamClient.new(url=STREAM_URL, validate=validate)
        ),
        ws=WsApi(
          client=SocketRpcClient.new(
            url=WS_API_URL,
            credentials=credentials,
            recv_window=recv_window,
            validate=validate,
          )
        ),
      ),
      usdm_futures=UsdMFutures(
        http=UsdMFuturesHttp(
          client=HttpRpcClient(
            base_url=USDM_FUTURES_URL,
            credentials=credentials,
            recv_window=recv_window,
            validate=validate,
          )
        ),
        streams=UsdMFuturesStreams(
          client=SocketStreamClient.new(url=USDM_FUTURES_STREAM_URL, validate=validate)
        ),
        public_streams=UsdMFuturesPublicStreams(
          client=SocketStreamClient.new(
            url=USDM_FUTURES_PUBLIC_STREAM_URL, validate=validate
          )
        ),
        private_streams=UsdMFuturesPrivateStreams(
          client=PrivateStreamSocketClient(
            base_url=USDM_FUTURES_PRIVATE_STREAM_URL, validate=validate
          )
        ),
        ws=UsdMFuturesWsApi(
          client=SocketRpcClient.new(
            url=USDM_FUTURES_WS_API_URL,
            credentials=credentials,
            recv_window=recv_window,
            validate=validate,
          )
        ),
      ),
      coinm_futures=CoinMFutures(
        http=CoinMFuturesHttp(
          client=HttpRpcClient(
            base_url=COINM_FUTURES_URL,
            credentials=credentials,
            recv_window=recv_window,
            validate=validate,
          )
        ),
        streams=CoinMFuturesStreams(
          client=SocketStreamClient.new(url=COINM_FUTURES_STREAM_URL, validate=validate)
        ),
        ws=CoinMFuturesWsApi(
          client=SocketRpcClient.new(
            url=COINM_FUTURES_WS_API_URL,
            credentials=credentials,
            recv_window=recv_window,
            validate=validate,
          )
        ),
      ),
      options=Options(
        http=OptionsHttp(
          client=HttpRpcClient(
            base_url=OPTIONS_URL,
            credentials=credentials,
            recv_window=recv_window,
            validate=validate,
          )
        ),
        streams=OptionsStreams(
          client=SocketStreamClient.new(url=OPTIONS_STREAM_URL, validate=validate)
        ),
        private_streams=OptionsPrivateStreams(
          client=PrivateStreamSocketClient(
            base_url=OPTIONS_PRIVATE_STREAM_URL, validate=validate
          )
        ),
      ),
      portfolio_margin=PortfolioMargin(
        http=PortfolioMarginHttp(
          client=HttpRpcClient(
            base_url=PORTFOLIO_MARGIN_URL,
            credentials=credentials,
            recv_window=recv_window,
            validate=validate,
          )
        ),
        private_streams=PortfolioMarginPrivateStreams(
          client=PrivateStreamSocketClient(
            base_url=PORTFOLIO_MARGIN_PRIVATE_STREAM_URL, validate=validate
          )
        ),
      ),
    )

  async def __aenter__(self):
    await asyncio.gather(
      self.spot.__aenter__(),
      self.usdm_futures.__aenter__(),
      self.coinm_futures.__aenter__(),
      self.options.__aenter__(),
      self.portfolio_margin.__aenter__(),
    )
    return self

  async def __aexit__(self, exc_type, exc_value, traceback):
    await asyncio.gather(
      self.spot.__aexit__(exc_type, exc_value, traceback),
      self.usdm_futures.__aexit__(exc_type, exc_value, traceback),
      self.coinm_futures.__aexit__(exc_type, exc_value, traceback),
      self.options.__aexit__(exc_type, exc_value, traceback),
      self.portfolio_margin.__aexit__(exc_type, exc_value, traceback),
    )
