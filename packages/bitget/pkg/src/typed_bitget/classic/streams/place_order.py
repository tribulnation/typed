PlaceOrderParams = (
  SpotPlaceOrderLimitParams
  | SpotPlaceOrderMarketParams
  | MixPlaceOrderLimitParams
  | MixPlaceOrderMarketParams
)
"""Order parameters, shaped differently for spot vs mix (`inst_type`-discriminated) and
for limit vs market (`orderType`-discriminated).
"""


class PlaceOrderResult(TypedDict):
  """Result of the order placement."""

  orderId: str
  """ID of the placed order."""
  clientOid: NotRequired[str]
  """Echoed custom order ID."""


class PlaceOrderReplyArg(TypedDict):
  """One echoed command result."""

  id: str
  """Echoed command identifier."""
  instType: InstType
  """Product line type."""
  channel: Literal['place-order']
  """Command name."""
  instId: str
  """Product ID."""
  params: PlaceOrderResult
  """Result of the order placement."""


class PlaceOrderReply(TypedDict):
  """Reply to the `place-order` command -- the one answering frame."""

  event: Literal['trade', 'error']
  """Event name: `trade` on success, `error` on failure."""
  arg: list[PlaceOrderReplyArg]
  """Echoed command result(s)."""
  code: str | int
  """Result code; docs show `0` (integer) on success."""
  msg: str
  """Result message, e.g. `"Success"`."""


class PlaceOrder(StreamEndpoint):
  """`classic_streams.place_order`."""

  async def place_order(
    self, inst_type: InstType, inst_id: str, params: PlaceOrderParams,
  ) -> PlaceOrderReply:
    """Place a single spot or mix order over the private WebSocket connection, as a
    lower-latency alternative to the REST order-placement endpoints. Requires the
    `login` handshake first (automatic, on first authed call on this connection).

    Args:
      inst_type: Product line type: `SPOT`, or a futures product type
        (`USDT-FUTURES`, `COIN-FUTURES`, `USDC-FUTURES`).
      inst_id: Product ID, e.g. `BTCUSDT`.
      params: Spot or mix order-placement parameters, `inst_type`-discriminated, further
        split into limit/market variants by `orderType`.

    References:
      - [Official docs](https://www.bitget.com/api-doc/classic/spot/websocket/private/Place-Order-Channel)
    """
    req = {
      'op': 'trade',
      'args': [
        {
          'instType': inst_type,
          'instId': inst_id,
          'channel': 'place-order',
          'params': params,
        }
      ],
    }
    return await self.authed_command(req, validator=validator(PlaceOrderReply))
