"""`classic_streams.place_order` -- hand-written, not codegen'd.

`id` is not a caller-facing parameter: `BaseSocketConnection` manages a trade command's
correlation id internally (`rpc_send`/`parse_msg`, see `core/transport/ws/common.py`),
the same way an HTTP request never asks the caller for anything to correlate a reply
with. That's structurally different from every REST/subscription endpoint's flat
`requestBody`-as-one-parameter shape, so this can't be generated by the shared codegen
backend -- `clients/bitget/spec/endpoints/classic_streams/place_order/endpoint.json`
declares `surface: {kind: "handwritten", symbol: "classic.streams.place_order:PlaceOrder"}`
accordingly.
"""

from typing_extensions import Literal, NotRequired, Required
from typed_core.validation import TypedDict, validator

from ...core.endpoint.stream import StreamEndpoint

